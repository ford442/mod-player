#!/usr/bin/env node
/**
 * FX character stage: hand-written TypeScript worklet vs Faust (#453 ADR,
 * docs/ADR-fx-character-dsp.md). A measurement script, not a test.
 *
 *   npm i --no-save @grame/faustwasm@0.19.0    # 31 MB; never a project dependency
 *   node scripts/bench-fx-character.mjs
 *
 * 1. Writes bench/faust/halfband_taps.lib from the TS halfband design.
 * 2. Compiles bench/faust/character.dsp with libfaust-wasm (build time — no
 *    Faust compiler would ship).
 * 3. Renders 60 s of stereo noise at 48 kHz in 128-frame quanta through both,
 *    every sub-stage on; median of 7 runs → ns per stereo frame and % of one
 *    core at 48 kHz.
 * 4. Equivalence: RMS difference of the two outputs after a 0.5 s settle, in
 *    dB below the output RMS.
 * 5. Shipped size: the TS worklet bundle vs Faust's wasm + glue (gzipped).
 *
 * Env: FAUSTWASM (module path, default '@grame/faustwasm'), BENCH_SECONDS,
 * BENCH_RUNS, FAUST_ARGS (e.g. "-double").
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { gzipSync } from 'node:zlib';
import * as esbuild from 'esbuild';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SR = 48000;
const QUANTUM = 128;
const SECONDS = Number(process.env.BENCH_SECONDS || 60);
const RUNS = Number(process.env.BENCH_RUNS || 7);
const FAUST_ARGS = process.env.FAUST_ARGS || '-ftz 2';

// Every sub-stage on, mid-range settings — the CPU worst case.
const PARAMS = { tapeOn: 1, drive: 0.6, bias: 0.15, ledOn: 1, ledModel: 0, crushOn: 1, crushRate: 11025, crushBits: 8, outputGain: -3 };

async function loadTsKernels() {
  const result = await esbuild.build({
    stdin: {
      contents: `export { CharacterChannel } from './audio-worklet/js/fx/characterChannel';
                 export { halfbandPhaseTaps } from './audio-worklet/js/fx/halfband';
                 export { characterParamArray } from './audio-worklet/fxCharacterParams';`,
      resolveDir: ROOT,
      loader: 'ts',
    },
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: 'es2020',
    write: false,
  });
  const url = `data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString('base64')}`;
  return import(url);
}

async function loadFaust() {
  const spec = process.env.FAUSTWASM || '@grame/faustwasm';
  let entry;
  try {
    entry = createRequire(join(ROOT, 'package.json')).resolve(spec);
  } catch {
    console.error(`Cannot find ${spec}. Install it without saving: npm i --no-save @grame/faustwasm@0.19.0`);
    process.exit(2);
  }
  const pkgDir = entry.slice(0, entry.lastIndexOf('/dist/'));
  const mod = await import(pathToFileURL(join(pkgDir, 'dist/esm/index.js')).href);
  return { mod, pkgDir };
}

function noise(frames, seed) {
  const out = new Float32Array(frames);
  let s = seed >>> 0;
  for (let i = 0; i < frames; i++) {
    s = (Math.imul(s, 1664525) + 1013904223) >>> 0;
    out[i] = (s / 0xffffffff - 0.5) * 0.8;
  }
  return out;
}

const median = (xs) => [...xs].sort((a, b) => a - b)[Math.floor(xs.length / 2)];

function benchTs(kernels, inL, inR) {
  const values = kernels.characterParamArray(PARAMS).map(Math.fround);
  const left = new kernels.CharacterChannel(SR, values);
  const right = new kernels.CharacterChannel(SR, values);
  const outL = new Float32Array(inL.length);
  const outR = new Float32Array(inR.length);
  const t0 = process.hrtime.bigint();
  for (let off = 0; off < inL.length; off += QUANTUM) {
    left.process(inL.subarray(off, off + QUANTUM), outL.subarray(off, off + QUANTUM), QUANTUM);
    right.process(inR.subarray(off, off + QUANTUM), outR.subarray(off, off + QUANTUM), QUANTUM);
    left.flushDenormals();
    right.flushDenormals();
  }
  const ns = Number(process.hrtime.bigint() - t0);
  return { ns, out: [outL, outR] };
}

async function benchFaust(generator, inL, inR) {
  const processor = await generator.createOfflineProcessor(SR, QUANTUM);
  for (const [name, value] of Object.entries(PARAMS)) {
    processor.setParamValue(`/character/${name}`, value);
  }
  const t0 = process.hrtime.bigint();
  const out = processor.render([inL, inR], inL.length);
  const ns = Number(process.hrtime.bigint() - t0);
  return { ns, out };
}

function rmsDb(a, b, from) {
  let diff = 0;
  let ref = 0;
  for (let c = 0; c < 2; c++) {
    for (let i = from; i < a[c].length; i++) {
      diff += (a[c][i] - b[c][i]) ** 2;
      ref += a[c][i] ** 2;
    }
  }
  return 10 * Math.log10(diff / ref);
}

async function main() {
  const kernels = await loadTsKernels();
  const taps = Array.from(kernels.halfbandPhaseTaps());
  writeFileSync(
    join(ROOT, 'bench/faust/halfband_taps.lib'),
    `// generated by scripts/bench-fx-character.mjs from audio-worklet/js/fx/halfband.ts — do not edit\n` +
      `halfband_even = (${taps.map((t) => t.toPrecision(17)).join(', ')});\n`,
  );

  const { mod, pkgDir } = await loadFaust();
  const faustModule = await mod.instantiateFaustModuleFromFile(join(pkgDir, 'libfaust-wasm/libfaust-wasm.js'));
  const compiler = new mod.FaustCompiler(new mod.LibFaust(faustModule));
  const dsp = readFileSync(join(ROOT, 'bench/faust/character.dsp'), 'utf8');
  const generator = new mod.FaustMonoDspGenerator();
  // The compiler resolves imports from its virtual FS: put the taps lib there.
  compiler.fs().writeFile('halfband_taps.lib', readFileSync(join(ROOT, 'bench/faust/halfband_taps.lib'), 'utf8'));
  await generator.compile(compiler, 'character', dsp, FAUST_ARGS);
  const factory = generator.factory;

  const frames = Math.round(SECONDS * SR);
  const inL = noise(frames, 1);
  const inR = noise(frames, 2);

  const tsNs = [];
  const faustNs = [];
  let tsOut;
  let faustOut;
  benchTs(kernels, inL.subarray(0, SR), inR.subarray(0, SR)); // warm-up
  await benchFaust(generator, inL.subarray(0, SR), inR.subarray(0, SR));
  for (let r = 0; r < RUNS; r++) {
    const ts = benchTs(kernels, inL, inR);
    const fa = await benchFaust(generator, inL, inR);
    tsNs.push(ts.ns);
    faustNs.push(fa.ns);
    tsOut = ts.out;
    faustOut = fa.out;
  }

  const tsMs = median(tsNs) / 1e6;
  const faustMs = median(faustNs) / 1e6;
  const settle = Math.round(0.5 * SR);
  const equivalence = rmsDb(tsOut, faustOut, settle);
  const tsBundle = readFileSync(join(ROOT, 'public/worklets/fx-character-worklet.js'));
  const faustWasm = Buffer.from(factory.code);
  const faustJson = Buffer.from(factory.json);

  const row = (label, ms) =>
    `${label.padEnd(20)} ${((ms * 1e6) / frames).toFixed(1).padStart(8)} ns/frame  ${((100 * ms) / (SECONDS * 1000)).toFixed(2).padStart(6)} % of a core`;
  console.log(`FX character stage, ${SECONDS} s stereo @ ${SR} Hz, ${QUANTUM}-frame quanta, median of ${RUNS} (Faust args: ${FAUST_ARGS})`);
  console.log(row('TypeScript worklet', tsMs));
  console.log(row('Faust wasm', faustMs));
  console.log(`Faust / TS CPU         ${(faustMs / tsMs).toFixed(2)}×`);
  console.log(`Equivalence            ${equivalence.toFixed(1)} dB (RMS difference below output, after 0.5 s)`);
  console.log(`Shipped, gzipped       TS ${(gzipSync(tsBundle).length / 1024).toFixed(1)} KB | Faust wasm ${(gzipSync(faustWasm).length / 1024).toFixed(1)} KB + JSON ${(gzipSync(faustJson).length / 1024).toFixed(1)} KB (+ faustwasm runtime glue)`);
  console.log(JSON.stringify({ tsMs, faustMs, ratio: faustMs / tsMs, equivalenceDb: equivalence, node: process.version }));
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
