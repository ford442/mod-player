#!/usr/bin/env node
/**
 * Compile the AudioWorklet processors from TypeScript to the classic scripts
 * that `audioWorklet.addModule()` loads.
 *
 *   src/worklets/openmpt-processor.ts  →  public/worklets/openmpt-worklet.js
 *   src/worklets/native-bridge.ts      →  public/worklets/native-bridge-processor.js
 *
 * Why esbuild and not Vite: AudioWorkletGlobalScope cannot `import()` or
 * `importScripts()`, so the output must be a single self-contained IIFE with no
 * module syntax. Bundling is what lets the processor share the protocol
 * constants / message guard / SAB layout with the main thread as real TS
 * imports instead of a hand-mirrored classic script.
 *
 * Never minified: tests/workletRegressionGuards.test.ts and
 * tests/workletAudioLifecycle.test.ts pattern-match the generated file to keep
 * the #329/#330/#354 audio invariants locked (60 Hz position posts, no
 * per-quantum allocation, singleton libopenmpt init).
 *
 * Usage:
 *   node scripts/build-worklet-js.mjs           # write the outputs
 *   node scripts/build-worklet-js.mjs --check   # fail if outputs are stale
 */
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');

/**
 * esbuild ships with Vite (a declared devDependency) — no extra install, and
 * deliberately NOT a direct dependency: pinning it at the root collapses the
 * nested copy Vitest's own Vite needs as a peer. Resolve it through Vite so the
 * script works whether npm hoists esbuild or nests it.
 */
function loadEsbuild() {
  const candidates = [
    () => require.resolve('esbuild'),
    () => require.resolve('esbuild', {
      paths: [dirname(require.resolve('vite/package.json', { paths: [ROOT] }))],
    }),
  ];
  for (const resolveEsbuild of candidates) {
    try {
      return require(resolveEsbuild());
    } catch {
      /* try the next resolution path */
    }
  }
  throw new Error(
    'Could not resolve esbuild (it ships with vite). Run `npm install` first.',
  );
}

const { build } = loadEsbuild();

/** Source of record → generated classic script. */
export const WORKLET_BUNDLES = [
  {
    entry: 'src/worklets/openmpt-processor.ts',
    outfile: 'public/worklets/openmpt-worklet.js',
  },
  {
    entry: 'src/worklets/native-bridge.ts',
    outfile: 'public/worklets/native-bridge-processor.js',
  },
];

const GENERATED_MARKER = '@generated by scripts/build-worklet-js.mjs';

function banner(entry) {
  return [
    '// ─────────────────────────────────────────────────────────────────────────',
    `// ${GENERATED_MARKER} — DO NOT EDIT.`,
    `// Source of record: ${entry}`,
    '// Rebuild: npm run build:worklet-js   (verify: npm run verify:worklet-js)',
    '// Bump WORKLET_VERSION in hooks/useWorkletLoader.ts whenever this changes.',
    '// ─────────────────────────────────────────────────────────────────────────',
    '',
  ].join('\n');
}

async function bundleOne({ entry, outfile }) {
  const result = await build({
    entryPoints: [join(ROOT, entry)],
    bundle: true,
    write: false,
    format: 'iife',
    platform: 'browser',
    target: 'es2020',
    charset: 'utf8',
    minify: false,
    legalComments: 'inline',
    tsconfig: join(ROOT, 'tsconfig.worklet.json'),
    banner: { js: banner(entry) },
    logLevel: 'silent',
  });
  const [out] = result.outputFiles;
  return out.text;
}

async function main() {
  const check = process.argv.includes('--check');
  let stale = 0;

  for (const bundle of WORKLET_BUNDLES) {
    const text = await bundleOne(bundle);
    const target = join(ROOT, bundle.outfile);

    if (check) {
      let current = null;
      try {
        current = readFileSync(target, 'utf8');
      } catch {
        current = null;
      }
      if (current !== text) {
        stale += 1;
        console.error(
          `❌ ${bundle.outfile} is stale (does not match ${bundle.entry}).\n` +
          '   Run: npm run build:worklet-js  — then commit the generated file.',
        );
      } else {
        console.log(`✅ ${bundle.outfile} matches ${bundle.entry}`);
      }
      continue;
    }

    writeFileSync(target, text);
    console.log(
      `✅ ${relative(ROOT, target)}  ←  ${bundle.entry}  ` +
      `(${(text.length / 1024).toFixed(1)} kB)`,
    );
  }

  if (stale > 0) {
    process.exitCode = 1;
  }
}

main().catch((err) => {
  console.error('[build-worklet-js] failed:', err);
  process.exitCode = 1;
});
