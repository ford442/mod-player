#!/usr/bin/env node
/**
 * The tracker-module file extensions the app accepts, read from the libopenmpt it ships.
 *
 *   node scripts/gen-module-formats.mjs           # (re)write utils/moduleFormats.generated.ts + public/sw.js's list
 *   node scripts/gen-module-formats.mjs --check   # exit 1 if either is stale
 *
 * Boots the committed release pair (public/worklets/libopenmpt-worklet.{js,wasm}) in Node and calls
 * openmpt_get_supported_extensions(). scripts/build-js-libopenmpt.sh runs it after a release
 * (non-playback) build; tests/wasm/moduleFormats.test.ts fails when the committed files drift.
 * Every picker `accept`, drop filter, folder import and remote-URL check goes through
 * utils/moduleFormats.ts, so one list is the truth.
 *
 * public/sw.js is a plain static file (no bundler), so its copy of the list lives between the
 * `// <module-formats>` markers and is rewritten here too.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { REPO_ROOT, resolveArtifactPaths } from './jsEngineArtifacts.mjs';

export const GENERATED_TS_REL = 'utils/moduleFormats.generated.ts';
export const SW_REL = 'public/sw.js';
const SW_BEGIN = '// <module-formats> generated by scripts/gen-module-formats.mjs — do not edit';
const SW_END = '// </module-formats>';

/**
 * Boot the committed glue + wasm on this globalThis (restored afterwards) and return
 * openmpt_get_supported_extensions() as libopenmpt orders it.
 * @param {{ root?: string }} [options]
 * @returns {Promise<string[]>}
 */
export async function readSupportedExtensions({ root = REPO_ROOT } = {}) {
  const p = resolveArtifactPaths(root);
  const glueText = readFileSync(p.glue, 'utf8');
  const wasmBinary = readFileSync(p.wasm);
  const g = /** @type {Record<string, any>} */ (globalThis);
  const previous = g.libopenmpt;
  g.libopenmpt = { noInitialRun: true, wasmBinary };
  try {
    new Function(glueText.replace(/^\s*export\s+(default\s+)?/gm, '')).call(globalThis);
    const lib = g.libopenmpt;
    await new Promise((res, rej) => {
      const timer = setTimeout(() => rej(new Error('libopenmpt runtime init timeout (30s)')), 30000);
      const done = () => {
        clearTimeout(timer);
        res(undefined);
      };
      if (lib.calledRun) done();
      else lib.onRuntimeInitialized = done;
    });
    const ptr = lib._openmpt_get_supported_extensions();
    if (!ptr) throw new Error('openmpt_get_supported_extensions() returned NULL');
    const list = String(lib.UTF8ToString(ptr));
    lib._openmpt_free_string(ptr);
    const exts = list
      .split(';')
      .map((e) => e.trim().toLowerCase())
      .filter((e) => e.length > 0);
    if (exts.length === 0) throw new Error('openmpt_get_supported_extensions() returned an empty list');
    return exts;
  } finally {
    if (previous === undefined) delete g.libopenmpt;
    else g.libopenmpt = previous;
  }
}

/**
 * Sorted, de-duplicated; one JSON-ish line per extension so a libopenmpt bump diffs readably.
 * @param {string[]} exts
 */
export function normalizeExtensions(exts) {
  return [...new Set(exts)].sort();
}

/**
 * @param {string[]} exts
 * @param {string} libopenmptVersion
 */
export function renderGeneratedTs(exts, libopenmptVersion) {
  const lines = normalizeExtensions(exts).map((e) => `  '${e}',`);
  return `// generated by scripts/gen-module-formats.mjs — do not edit.
// openmpt_get_supported_extensions() of the committed public/worklets/libopenmpt-worklet.wasm
// (libopenmpt ${libopenmptVersion}). Use the helpers in utils/moduleFormats.ts, not this list directly.

/** Lower-case module file extensions (no dot) the shipped libopenmpt loads, sorted. */
export const LIBOPENMPT_MODULE_EXTENSIONS = [
${lines.join('\n')}
] as const;
`;
}

/**
 * @param {string} swText
 * @param {string[]} exts
 */
export function renderServiceWorker(swText, exts) {
  const begin = swText.indexOf(SW_BEGIN);
  const end = swText.indexOf(SW_END);
  if (begin < 0 || end < begin) {
    throw new Error(`${SW_REL}: missing the "${SW_BEGIN}" … "${SW_END}" markers`);
  }
  const indent = swText.slice(swText.lastIndexOf('\n', begin) + 1, begin);
  const block = [
    SW_BEGIN,
    `${indent}const MODULE_EXTENSIONS = ${JSON.stringify(normalizeExtensions(exts))};`,
    `${indent}`,
  ].join('\n');
  return swText.slice(0, begin) + block + swText.slice(end);
}

function readLibopenmptVersion(root) {
  const manifest = JSON.parse(readFileSync(join(root, 'audio-worklet/js/libopenmpt-worklet.generated.json'), 'utf8'));
  return String(manifest.libopenmpt ?? 'unknown');
}

/**
 * Expected contents of the generated TS file and public/sw.js, from the committed wasm.
 * @param {{ root?: string }} [options]
 */
export async function expectedOutputs({ root = REPO_ROOT } = {}) {
  const exts = await readSupportedExtensions({ root });
  return {
    exts,
    ts: renderGeneratedTs(exts, readLibopenmptVersion(root)),
    sw: renderServiceWorker(readFileSync(join(root, SW_REL), 'utf8'), exts),
  };
}

/**
 * The repo-relative paths whose committed contents differ from what the wasm says.
 * @param {{ root?: string }} [options]
 * @returns {Promise<string[]>}
 */
export async function staleOutputs({ root = REPO_ROOT } = {}) {
  const { ts, sw } = await expectedOutputs({ root });
  const stale = [];
  let currentTs = '';
  try {
    currentTs = readFileSync(join(root, GENERATED_TS_REL), 'utf8');
  } catch {
    /* missing → stale */
  }
  if (currentTs !== ts) stale.push(GENERATED_TS_REL);
  if (readFileSync(join(root, SW_REL), 'utf8') !== sw) stale.push(SW_REL);
  return stale;
}

async function main() {
  const check = process.argv.includes('--check');
  if (check) {
    const stale = await staleOutputs();
    if (stale.length > 0) {
      console.error(`gen-module-formats --check FAILED: stale vs the committed libopenmpt wasm: ${stale.join(', ')}`);
      console.error('  run: node scripts/gen-module-formats.mjs');
      process.exit(1);
    }
    console.log('gen-module-formats --check OK');
    return;
  }
  const { exts, ts, sw } = await expectedOutputs();
  writeFileSync(join(REPO_ROOT, GENERATED_TS_REL), ts);
  writeFileSync(join(REPO_ROOT, SW_REL), sw);
  console.log(`gen-module-formats: ${normalizeExtensions(exts).length} extensions → ${GENERATED_TS_REL}, ${SW_REL}`);
}

if (process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href) {
  await main();
}
