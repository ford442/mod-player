/// <reference lib="webworker" />

// Service Worker for MOD Player
// This SW is scope-aware and works under any base path (e.g., /xm-player/)

// v6: libmpt/ (wasm2js) → worklets/libopenmpt-worklet.{js,wasm}; also purges the old libmpt cache entries.
// v7: COEP credentialless → require-corp; evicts the cached index.html that replays the old COEP offline.
const CACHE_NAME = 'mod-player-v7';

// Get the scope (base path) from the service worker's registration
const getScope = () => self.registration.scope || '/';

// Build precache URLs relative to the scope
const getPrecacheUrls = () => {
  const scope = getScope();
  // Ensure scope ends with /
  const base = scope.endsWith('/') ? scope : scope + '/';
  // libopenmpt-worklet.{js,wasm} are NOT precached: they are requested with a content-hash ?v=
  // (utils/libopenmptAssets.ts), so an unversioned precache entry would never match. They are
  // cached on first use below, keyed by that versioned URL, so a rebuilt .wasm can never be
  // served next to a stale glue.
  return [
    base,
    base + 'index.html',
  ];
};

// Module file extensions libopenmpt loads (cache-first below). The list between the markers is
// rewritten from the shipped wasm by scripts/gen-module-formats.mjs (this file is not bundled).
// <module-formats> generated by scripts/gen-module-formats.mjs — do not edit
const MODULE_EXTENSIONS = ["667","669","amf","ams","c67","cba","dbm","digi","dmf","dsm","dsym","dtm","etx","far","fc","fc13","fc14","fmt","fst","ftm","gdm","gmc","gt2","gtk","ice","imf","ims","it","j2b","m15","mdl","med","mmcmp","mms","mo3","mod","mptm","mt2","mtm","mus","nst","okt","oxm","plm","ppm","psm","pt36","ptm","puma","rtm","s3m","sfx","sfx2","smod","st26","stk","stm","stp","stx","symmod","tcb","ult","umx","unic","wow","xm","xmf","xpk"];
// </module-formats>
const MODULE_EXTENSION_SET = new Set(MODULE_EXTENSIONS);

const isModulePath = (pathname) => {
  const m = /\.([a-z0-9]+)$/i.exec(pathname);
  return m !== null && MODULE_EXTENSION_SET.has(m[1].toLowerCase());
};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(getPrecacheUrls()))
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k)))
    )
  );
  self.clients.claim();
});

self.addEventListener('fetch', (event) => {
  // Cache module files (every extension libopenmpt loads) and WASM
  const url = new URL(event.request.url);
  const isLibOpenMPT = /\/worklets\/libopenmpt-worklet\.(js|wasm)$/i.test(url.pathname);
  const isModuleFile = /\.wasm$/i.test(url.pathname) || isModulePath(url.pathname);

  if (isLibOpenMPT || isModuleFile) {
    // Cache-first for module files
    event.respondWith(
      caches.match(event.request).then((cached) => {
        if (cached) return cached;
        return fetch(event.request).then((response) => {
          if (response.ok) {
            const clone = response.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(event.request, clone));
          }
          return response;
        });
      })
    );
  } else {
    // Network-first for everything else
    event.respondWith(
      fetch(event.request).catch(() => caches.match(event.request).then((r) => r || new Response('Offline', { status: 503 })))
    );
  }
});
